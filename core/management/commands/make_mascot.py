"""Write the mascot files from core/mascot.py: static/mascot/*.svg and the site rig templates/includes/mascot_rig.svg.

    python manage.py make_mascot

Rerun after changing core/mascot.py and commit the result (the files are served as they are).
"""
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from core import mascot


class Command(BaseCommand):
    help = "Generate the giraffe mascot SVG files"

    def handle(self, *args, **options):
        out = Path(settings.BASE_DIR) / "static" / "mascot"
        out.mkdir(parents=True, exist_ok=True)
        for name, svg in mascot.all_files().items():
            (out / name).write_text(svg + "\n", encoding="utf-8")
            self.stdout.write(f"{out / name}  {len(svg) // 1024 + 1} KB")
        rig = Path(settings.BASE_DIR) / "templates" / "includes" / "mascot_rig.svg"
        rig.write_text("{# generated by manage.py make_mascot from core/mascot.py — do not edit #}" + mascot.rig() + "\n",
                       encoding="utf-8")
        self.stdout.write(f"{rig}  {len(rig.read_text()) // 1024 + 1} KB")
